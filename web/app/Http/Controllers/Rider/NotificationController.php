<?php

namespace App\Http\Controllers\Rider;

use App\Http\Controllers\Controller;
use Illuminate\Http\JsonResponse;
use Illuminate\Http\RedirectResponse;
use Illuminate\Http\Request;
use Illuminate\Notifications\DatabaseNotification;
use Illuminate\View\View;

/**
 * Rider notification centre.
 *
 * Every query is scoped through the signed-in rider's own `notifications()`
 * relation, so a rider can never read, mark or open another rider's rows.
 * The routes live inside the `auth:rider` + `rider.active` group, which means
 * a suspended rider cannot reach an operational page through a notification
 * link either.
 */
class NotificationController extends Controller
{
    public function index(Request $request): View
    {
        $rider = $request->user('rider');

        return view('Rider.Notifications.index', [
            'notifications' => $rider->notifications()->latest()->paginate(20),
            'unreadCount' => $rider->unreadNotifications()->count(),
        ]);
    }

    /**
     * Lightweight polling payload for the dashboard bell.
     */
    public function recent(Request $request): JsonResponse
    {
        $rider = $request->user('rider');

        $notifications = $rider->notifications()
            ->latest()
            ->limit(8)
            ->get()
            ->map(fn (DatabaseNotification $notification): array => $this->present($notification))
            ->values();

        return response()->json([
            'unread_count' => $rider->unreadNotifications()->count(),
            'notifications' => $notifications,
        ]);
    }

    public function count(Request $request): JsonResponse
    {
        return response()->json([
            'count' => $request->user('rider')->unreadNotifications()->count(),
        ]);
    }

    public function markRead(Request $request, string $notification): JsonResponse|RedirectResponse
    {
        $this->owned($request, $notification)->markAsRead();

        return $this->readResponse($request, 'Notification marked as read.');
    }

    public function markAllRead(Request $request): JsonResponse|RedirectResponse
    {
        $request->user('rider')->unreadNotifications()->update(['read_at' => now()]);

        return $this->readResponse($request, 'All notifications marked as read.');
    }

    /**
     * Mark the notification read and continue to the page it points at.
     *
     * The stored URL is generated by this application, but it is still
     * validated against the rider panel prefix so a tampered payload can never
     * turn the endpoint into an open redirect.
     */
    public function open(Request $request, string $notification): RedirectResponse
    {
        $row = $this->owned($request, $notification);

        if ($row->read_at === null) {
            $row->markAsRead();
        }

        return redirect()->to($this->safeRiderUrl(data_get($row->data, 'url')));
    }

    private function owned(Request $request, string $id): DatabaseNotification
    {
        $row = $request->user('rider')->notifications()->whereKey($id)->first();

        abort_if($row === null, 404);

        return $row;
    }

    private function readResponse(Request $request, string $message): JsonResponse|RedirectResponse
    {
        if ($request->expectsJson()) {
            return response()->json([
                'success' => true,
                'unread_count' => $request->user('rider')->unreadNotifications()->count(),
            ]);
        }

        return back()->with('success', $message);
    }

    /** @return array<string, mixed> */
    private function present(DatabaseNotification $notification): array
    {
        $data = $notification->data ?? [];

        return [
            'id' => $notification->id,
            'type' => $data['type'] ?? 'notification',
            'title' => $data['title'] ?? 'Notification',
            'message' => $data['message'] ?? '',
            'url' => $this->safeRiderUrl($data['url'] ?? null),
            'open_url' => route('rider.notifications.open', $notification->id),
            'read' => $notification->read_at !== null,
            'created_at' => $notification->created_at?->toIso8601String(),
            'created_at_human' => $notification->created_at?->diffForHumans(),
        ];
    }

    private function safeRiderUrl(mixed $url): string
    {
        $fallback = route('rider.notifications.index');

        if (! is_string($url) || $url === '' || str_contains($url, '..') || str_contains($url, '\\')) {
            return $fallback;
        }

        $base = rtrim(url('/rider'), '/');

        if ($url === $base || str_starts_with($url, $base.'/')) {
            return $url;
        }

        // Relative form, e.g. "/rider/pickups".
        if (str_starts_with($url, '/rider/')) {
            return $url;
        }

        return $fallback;
    }
}
